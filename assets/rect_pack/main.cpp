#include "rect_pack.h"
#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <string>
#include <vector>

#define STB_IMAGE_IMPLEMENTATION
#include "../../util/stb/stb_image.h"
#define STB_IMAGE_WRITE_IMPLEMENTATION
#include "../../util/stb/stb_image_write.h"

namespace fs = std::filesystem;

static const char *const TEX_DIR = "assets/textures";
static const char *const OUT_DIR = "assets/atlas";
static const char *const HEADER_PATH = "atlas.h";
// Atlas path prefix as seen from the game's working directory
static const char *const GAME_DIR = "assets/atlas/";

static const int ATLAS_SIZE = 2048; // every sheet is exactly this size
static const int MARGIN = 1;  // empty space between images
static const int BORDER = 1;  // empty space at sheet edges
static const int PADDING = 2; // empty space around each image

struct image {
	std::string name;
	int w, h;
	unsigned char *pixels;
	int atlas, x, y;
};

static std::string c_escape(const std::string &s)
{
	std::string out;
	for (char c : s) {
		if (c == '"' || c == '\\')
			out += '\\';
		out += c;
	}
	return out;
}

// Copies img into sheet at (img.x, img.y)
static void blit(unsigned char *sheet, int sheet_w, const image &img)
{
	for (int y = 0; y < img.h; y++) {
		const unsigned char *src = img.pixels + y * img.w * 4;
		unsigned char *dst = sheet + ((img.y + y) * sheet_w + img.x) * 4;
		std::copy(src, src + img.w * 4, dst);
	}
}

int main()
{
	std::vector<image> images;
	for (const auto &entry : fs::directory_iterator(TEX_DIR)) {
		if (!entry.is_regular_file() || entry.path().extension() != ".png")
			continue;
		image img = {};
		img.name = entry.path().stem().string();
		img.pixels = stbi_load(entry.path().c_str(), &img.w, &img.h, nullptr, 4);
		if (!img.pixels) {
			fprintf(stderr, "failed to load %s: %s\n", entry.path().c_str(), stbi_failure_reason());
			return 1;
		}
		images.push_back(img);
	}
	if (images.empty()) {
		fprintf(stderr, "no .png files in %s\n", TEX_DIR);
		return 1;
	}
	std::sort(images.begin(), images.end(),
		[](const image &a, const image &b) { return a.name < b.name; });

	std::vector<rect_pack::Size> sizes;
	for (size_t i = 0; i < images.size(); i++) {
		int w = images[i].w + PADDING * 2 + MARGIN;
		int h = images[i].h + PADDING * 2 + MARGIN;
		if (w - MARGIN > ATLAS_SIZE - BORDER * 2 || h - MARGIN > ATLAS_SIZE - BORDER * 2) {
			fprintf(stderr, "%s is too large (%dx%d)\n", images[i].name.c_str(), images[i].w, images[i].h);
			return 1;
		}
		sizes.push_back({(int)i, w, h});
	}

	rect_pack::Settings settings = {};
	settings.method = rect_pack::Method::Best;
	settings.max_sheets = 0;
	settings.power_of_two = true;
	settings.allow_rotate = false;
	settings.border_padding = BORDER;
	settings.over_allocate = MARGIN;
	settings.max_width = ATLAS_SIZE;
	settings.max_height = ATLAS_SIZE;
	settings.min_width = ATLAS_SIZE;
	settings.min_height = ATLAS_SIZE;

	std::vector<rect_pack::Sheet> sheets = rect_pack::pack(settings, sizes);

	size_t packed = 0;
	for (const auto &s : sheets)
		packed += s.rects.size();
	if (packed != images.size()) {
		fprintf(stderr, "packed %zu of %zu images\n", packed, images.size());
		return 1;
	}

	fs::create_directories(OUT_DIR);
	std::vector<std::string> atlas_names;
	for (size_t s = 0; s < sheets.size(); s++) {
		const rect_pack::Sheet &sheet = sheets[s];
		std::vector<unsigned char> pixels((size_t)sheet.width * sheet.height * 4, 0);
		for (const auto &r : sheet.rects) {
			image &img = images[r.id];
			img.atlas = (int)s;
			img.x = r.x + PADDING;
			img.y = r.y + PADDING;
			blit(pixels.data(), sheet.width, img);
		}

		std::string name = "atlas_" + std::to_string(s) + ".png";
		std::string path = std::string(OUT_DIR) + "/" + name;
		if (!stbi_write_png(path.c_str(), sheet.width, sheet.height, 4, pixels.data(), sheet.width * 4)) {
			fprintf(stderr, "failed to write %s\n", path.c_str());
			return 1;
		}
		atlas_names.push_back(name);
		printf("%s: %dx%d, %zu images\n", path.c_str(), sheet.width, sheet.height, sheet.rects.size());
	}

	FILE *f = fopen(HEADER_PATH, "w");
	if (!f) {
		fprintf(stderr, "failed to open %s\n", HEADER_PATH);
		return 1;
	}
	fprintf(f, "// Generated by assets/rect_pack, do not edit.\n");
	fprintf(f, "#pragma once\n\n");
	fprintf(f, "#define ATLAS_COUNT %zu\n", sheets.size());
	fprintf(f, "#define ATLAS_IMAGE_COUNT %zu\n\n", images.size());

	fprintf(f, "struct atlas_sheet {\n");
	fprintf(f, "\tconst char *path;\n");
	fprintf(f, "\tint w, h;\n");
	fprintf(f, "};\n\n");

	fprintf(f, "// u0, v0 top left, u1, v1 bottom right\n");
	fprintf(f, "struct atlas_image {\n");
	fprintf(f, "\tconst char *name;\n");
	fprintf(f, "\tint atlas;\n");
	fprintf(f, "\tint x, y, w, h;\n");
	fprintf(f, "\tfloat u0, v0, u1, v1;\n");
	fprintf(f, "};\n\n");

	fprintf(f, "static const struct atlas_sheet atlas_sheets[ATLAS_COUNT] = {\n");
	for (size_t s = 0; s < sheets.size(); s++)
		fprintf(f, "\t{\"%s%s\", %d, %d},\n", GAME_DIR, atlas_names[s].c_str(),
			sheets[s].width, sheets[s].height);
	fprintf(f, "};\n\n");

	fprintf(f, "static const struct atlas_image atlas_images[ATLAS_IMAGE_COUNT] = {\n");
	for (const auto &img : images) {
		float sw = (float)sheets[img.atlas].width;
		float sh = (float)sheets[img.atlas].height;
		fprintf(f, "\t{\"%s\", %d, %d, %d, %d, %d, %.9ff, %.9ff, %.9ff, %.9ff},\n",
			c_escape(img.name).c_str(), img.atlas, img.x, img.y, img.w, img.h,
			img.x / sw, img.y / sh, (img.x + img.w) / sw, (img.y + img.h) / sh);
	}
	fprintf(f, "};\n");
	fclose(f);

	for (auto &img : images)
		stbi_image_free(img.pixels);
	printf("%s: %zu images\n", HEADER_PATH, images.size());
	return 0;
}
